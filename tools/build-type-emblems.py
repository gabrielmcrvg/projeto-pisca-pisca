for name, rows in art.items():
    h = len(rows); w = max(len(r) for r in rows)
    rows = [r.ljust(w, '.') for r in rows]
    ox = (10 - w) // 2 + ((10 - w) % 2 and 0); oy = (10 - h) // 2
    # junta pixels vizinhos da mesma linha num retângulo só
    rects = []
    for y, row in enumerate(rows):
        x = 0
        while x < w:
            if row[x] == '#':
                s = x
                while x < w and row[x] == '#': x += 1
                rects.append(f'<rect x="{s+ox}" y="{y+oy}" width="{x-s}" height="1"/>')
            else: x += 1
    out.append(f'<symbol id="t-{name}" viewBox="0 0 10 10">{"".join(rects)}</symbol>')
